/**
 * Generates responsive WebP variants for every raster image in static/images
 * (JPEG/PNG/WebP masters - originals may already be WebP)
 * that is referenced from src/, and writes a manifest used by `responsive()`.
 *
 * Requires `cwebp` (brew install webp). Run: pnpm images
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { basename, extname, join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const IMAGES_DIR = join(ROOT, 'static/images');
const OUT_DIR = join(IMAGES_DIR, 'webp');
const SRC_DIR = join(ROOT, 'src');
const MANIFEST = join(SRC_DIR, 'lib/images/manifest.ts');

const WIDTHS = [400, 800, 1200, 1600];
const QUALITY = '78';

function walk(dir) {
	return readdirSync(dir).flatMap((name) => {
		const path = join(dir, name);
		return statSync(path).isDirectory() ? walk(path) : [path];
	});
}

function dimensions(file) {
	const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file], { encoding: 'utf8' });
	const [width, height] = [...out.matchAll(/pixel(?:Width|Height): (\d+)/g)].map((m) => Number(m[1]));
	return { width, height };
}

const sources = walk(SRC_DIR)
	.filter((f) => /\.(svelte|ts)$/.test(f) && f !== MANIFEST)
	.map((f) => readFileSync(f, 'utf8'))
	.join('\n');

const images = readdirSync(IMAGES_DIR)
	.filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
	.filter((f) => sources.includes(`/images/${f}`))
	.sort();

mkdirSync(OUT_DIR, { recursive: true });

const manifest = {};

for (const file of images) {
	const input = join(IMAGES_DIR, file);
	const name = basename(file, extname(file));
	const { width, height } = dimensions(input);
	const widths = WIDTHS.filter((w) => w < width);
	if (width <= WIDTHS.at(-1)) widths.push(width);

	for (const w of widths) {
		const output = join(OUT_DIR, `${name}-${w}.webp`);
		if (existsSync(output) && statSync(output).mtimeMs > statSync(input).mtimeMs) continue;
		const resize = w < width ? ['-resize', String(w), '0'] : [];
		execFileSync('cwebp', ['-quiet', '-q', QUALITY, '-m', '6', '-metadata', 'none', ...resize, input, '-o', output]);
	}

	manifest[`/images/${file}`] = { width, height, widths };
	console.log(`${file} ${width}x${height} -> ${widths.join(', ')}`);
}

writeFileSync(
	MANIFEST,
	`// Generated by scripts/optimize-images.mjs — do not edit by hand.\n` +
		`export const manifest: Record<string, { width: number; height: number; widths: number[] }> = ${JSON.stringify(manifest, null, '\t')};\n`
);
